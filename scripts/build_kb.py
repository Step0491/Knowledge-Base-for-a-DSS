#!/usr/bin/env python3
"""
build_kb.py
ETL pipeline to merge Spotify Audio Features, Smartwatch User Biometrics,
and Health Optimization Protocols, translating them into normalized Prolog facts.

Part of: "Knowledge Base for a DSS: Context-Aware Music Recommendation & Health-Routine Optimization"
"""

import json
import os
import sys
from pathlib import Path

def sanitize_atom(text: str) -> str:
    """Ensure a string can be safely emitted as a Prolog atom."""
    text = str(text).strip()
    if text.isidentifier() and text[0].islower():
        return text
    escaped = text.replace("'", "\\'")
    return f"'{escaped}'"

def format_list(items, is_atom=True) -> str:
    """Format a Python list as a Prolog list string."""
    if not items:
        return "[]"
    if is_atom:
        formatted = [sanitize_atom(x) for x in items]
    else:
        formatted = [repr(x) for x in items]
    return "[" + ", ".join(formatted) + "]"

def load_json_file(path: Path):
    if not path.exists():
        raise FileNotFoundError(f"Required input file missing: {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def main():
    root_dir = Path(__file__).resolve().parent.parent
    data_raw_dir = root_dir / "data" / "raw"
    data_proc_dir = root_dir / "data" / "processed"
    kb_dir = root_dir / "knowledge_base"

    data_proc_dir.mkdir(parents=True, exist_ok=True)
    kb_dir.mkdir(parents=True, exist_ok=True)

    tracks_file = data_raw_dir / "spotify_tracks.json"
    biometrics_file = data_raw_dir / "smartwatch_biometrics.json"
    routines_file = data_raw_dir / "health_routines.json"

    print(f"[*] Loading raw datasets from {data_raw_dir}...")
    tracks = load_json_file(tracks_file)
    biometrics = load_json_file(biometrics_file)
    routines = load_json_file(routines_file)

    # 1. Referential & Domain Validation
    print(f"[*] Validating domain boundaries for {len(tracks)} tracks, {len(biometrics)} biometric profiles, and {len(routines)} routines...")
    track_ids = set()
    for t in tracks:
        tid = t["track_id"]
        if tid in track_ids:
            raise ValueError(f"Duplicate track_id: {tid}")
        track_ids.add(tid)
        assert 30 <= t["bpm"] <= 240, f"Invalid BPM {t['bpm']} for {tid}"
        assert 0.0 <= t["valence"] <= 1.0, f"Invalid valence {t['valence']} for {tid}"
        assert 0.0 <= t["energy"] <= 1.0, f"Invalid energy {t['energy']} for {tid}"
        assert 0.0 <= t["instrumentalness"] <= 1.0, f"Invalid instrumentalness for {tid}"

    user_ids = set()
    for b in biometrics:
        uid = b["user_id"]
        if uid in user_ids:
            raise ValueError(f"Duplicate user_id: {uid}")
        user_ids.add(uid)
        assert 40 <= b["heart_rate_bpm"] <= 220, f"Invalid HR {b['heart_rate_bpm']} for {uid}"
        assert 0 <= b["stress_level"] <= 100, f"Invalid stress {b['stress_level']} for {uid}"

    # 2. Emit knowledge_base/kb_tracks.pl
    kb_tracks_path = kb_dir / "kb_tracks.pl"
    print(f"[*] Emitting Prolog facts to {kb_tracks_path}...")
    with open(kb_tracks_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Spotify Audio Features Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: track(Id, Title, Artist, Genre, BPM, Valence, Energy, Danceability, Acousticness, Instrumentalness, LoudnessDb, DurationS, Attributes).\n")
        f.write("%         track_acoustic(Id, Acousticness, Instrumentalness, LoudnessDb).\n")
        f.write("%         track_features(Id, BPM, Valence, Energy).\n")
        f.write("%         track_has_attribute(Id, Attribute).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic track/13.\n")
        f.write(":- dynamic track_acoustic/4.\n")
        f.write(":- dynamic track_features/4.\n")
        f.write(":- dynamic track_has_attribute/2.\n\n")

        for t in tracks:
            tid = sanitize_atom(t["track_id"])
            title = sanitize_atom(t["title"])
            artist = sanitize_atom(t["artist"])
            genre = sanitize_atom(t["genre"])
            bpm = float(t["bpm"])
            valence = float(t["valence"])
            energy = float(t["energy"])
            danceability = float(t["danceability"])
            acousticness = float(t["acousticness"])
            inst = float(t["instrumentalness"])
            loudness = float(t["loudness_db"])
            duration = int(t["duration_s"])
            attrs = format_list(t.get("health_attributes", []), is_atom=True)

            f.write(f"track({tid}, {title}, {artist}, {genre}, {bpm:.1f}, {valence:.2f}, {energy:.2f}, {danceability:.2f}, {acousticness:.2f}, {inst:.2f}, {loudness:.1f}, {duration}, {attrs}).\n")
            f.write(f"track_acoustic({tid}, {acousticness:.2f}, {inst:.2f}, {loudness:.1f}).\n")
            f.write(f"track_features({tid}, {bpm:.1f}, {valence:.2f}, {energy:.2f}).\n")
            for attr in t.get("health_attributes", []):
                f.write(f"track_has_attribute({tid}, {sanitize_atom(attr)}).\n")
            f.write("\n")

    # 3. Emit knowledge_base/kb_biometrics.pl
    kb_bio_path = kb_dir / "kb_biometrics.pl"
    print(f"[*] Emitting Prolog facts to {kb_bio_path}...")
    with open(kb_bio_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Smartwatch User Biometrics Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: user_biometrics(UserId, Name, Activity, HeartRate, RestingHR, HRV, StressLevel, GSR, CircadianPhase, Fatigue, TargetGoal, PreferredGenres).\n")
        f.write("%         user_baseline(UserId, RestingHR, HRV).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic user_biometrics/12.\n")
        f.write(":- dynamic user_baseline/3.\n\n")

        for b in biometrics:
            uid = sanitize_atom(b["user_id"])
            name = sanitize_atom(b["name"])
            act = sanitize_atom(b["current_activity"])
            hr = float(b["heart_rate_bpm"])
            rhr = float(b["resting_heart_rate"])
            hrv = float(b["hrv_rmssd_ms"])
            stress = float(b["stress_level"])
            gsr = float(b["galvanic_skin_response"])
            phase = sanitize_atom(b["circadian_phase"])
            fatigue = float(b["fatigue_index"])
            goal = sanitize_atom(b["target_health_goal"])
            genres = format_list(b.get("preferred_genres", []), is_atom=True)

            f.write(f"user_biometrics({uid}, {name}, {act}, {hr:.1f}, {rhr:.1f}, {hrv:.1f}, {stress:.1f}, {gsr:.1f}, {phase}, {fatigue:.1f}, {goal}, {genres}).\n")
            f.write(f"user_baseline({uid}, {rhr:.1f}, {hrv:.1f}).\n\n")

        # Contextual activity demand rules
        f.write("% Contextual typical physiological baselines for activity categories\n")
        f.write("activity_target_profile(high_stress_work, stress_reduction, 60.0, 75.0, low_arousal).\n")
        f.write("activity_target_profile(cardio_running, cardio_peak_performance, 135.0, 170.0, high_arousal).\n")
        f.write("activity_target_profile(deep_focus_study, deep_focus_flow, 65.0, 80.0, moderate_arousal).\n")
        f.write("activity_target_profile(post_workout_recovery, post_workout_recovery, 68.0, 88.0, recovery_mode).\n")
        f.write("activity_target_profile(sleep_preparation, sleep_induction, 52.0, 64.0, somnolent_mode).\n")
        f.write("activity_target_profile(active_commute, active_commute_energizer, 85.0, 110.0, positive_affect).\n\n")

    # 4. Emit knowledge_base/kb_routines.pl
    kb_routines_path = kb_dir / "kb_routines.pl"
    print(f"[*] Emitting Prolog facts to {kb_routines_path}...")
    with open(kb_routines_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Health-Routine Optimization Protocols Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: health_routine(Id, Name, TargetGoal, MinBPM, MaxBPM, MinValence, MaxValence, MinEnergy, MaxEnergy, MinInst, MaxLoudness, MinTargetHR, MaxTargetHR, TargetStressMax, ReqAttrs, IsoEnabled).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic health_routine/16.\n\n")

        for r in routines:
            rid = sanitize_atom(r["routine_id"])
            name = sanitize_atom(r["name"])
            goal = sanitize_atom(r["target_goal"])
            min_bpm = float(r["min_bpm"])
            max_bpm = float(r["max_bpm"])
            min_val = float(r["min_valence"])
            max_val = float(r["max_valence"])
            min_eng = float(r["min_energy"])
            max_eng = float(r["max_energy"])
            min_inst = float(r["min_instrumentalness"])
            max_loud = float(r["max_loudness_db"])
            min_thr = float(r["target_hr_range"][0])
            max_thr = float(r["target_hr_range"][1])
            max_stress = float(r["target_stress_max"])
            req_attrs = format_list(r.get("required_attributes", []), is_atom=True)
            iso = "true" if r.get("iso_principle_enabled", False) else "false"

            f.write(f"health_routine({rid}, {name}, {goal}, {min_bpm:.1f}, {max_bpm:.1f}, {min_val:.2f}, {max_val:.2f}, {min_eng:.2f}, {max_eng:.2f}, {min_inst:.2f}, {max_loud:.1f}, {min_thr:.1f}, {max_thr:.1f}, {max_stress:.1f}, {req_attrs}, {iso}).\n")

    # 5. Emit knowledge_base/load_kb.pl
    kb_loader_path = kb_dir / "load_kb.pl"
    print(f"[*] Emitting central loader to {kb_loader_path}...")
    with open(kb_loader_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Central Knowledge Base Loader Module\n")
        f.write("% Part of: Context-Aware Music Recommendation & Health-Routine Optimization DSS\n")
        f.write("% =========================================================================\n\n")
        f.write(":- module(load_kb, [\n")
        f.write("    track/13,\n")
        f.write("    track_acoustic/4,\n")
        f.write("    track_features/4,\n")
        f.write("    track_has_attribute/2,\n")
        f.write("    user_biometrics/12,\n")
        f.write("    user_baseline/3,\n")
        f.write("    activity_target_profile/5,\n")
        f.write("    health_routine/16\n")
        f.write("]).\n\n")
        f.write(":- consult('kb_tracks.pl').\n")
        f.write(":- consult('kb_biometrics.pl').\n")
        f.write(":- consult('kb_routines.pl').\n")

    # 6. Emit summary JSON in data/processed
    summary_path = data_proc_dir / "merged_kb_summary.json"
    summary = {
        "title": "KB for a DSS, Context-Aware Music Recommendation & Health-Routine Optimization",
        "total_tracks": len(tracks),
        "total_biometric_profiles": len(biometrics),
        "total_health_routines": len(routines),
        "genres": sorted(list({t["genre"] for t in tracks})),
        "average_bpm": round(sum(t["bpm"] for t in tracks) / len(tracks), 2),
        "average_valence": round(sum(t["valence"] for t in tracks) / len(tracks), 2),
        "average_energy": round(sum(t["energy"] for t in tracks) / len(tracks), 2),
        "biometrics_hr_range": [min(b["heart_rate_bpm"] for b in biometrics), max(b["heart_rate_bpm"] for b in biometrics)],
        "biometrics_stress_range": [min(b["stress_level"] for b in biometrics), max(b["stress_level"] for b in biometrics)]
    }
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"[+] Knowledge base compiled successfully. Summary written to {summary_path}")

if __name__ == "__main__":
    main()
