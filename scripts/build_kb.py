#!/usr/bin/env python3
"""
build_kb.py
ETL pipeline to merge European Tour Destinations, UNESCO World Heritage Sites,
and Inter-city Transit datasets, translating them into normalized Prolog facts.

Part of: "Knowledge Base for a DSS (Tourism, Cultural Heritage & Education)"
"""

import json
import os
import sys
from pathlib import Path

def sanitize_atom(text: str) -> str:
    """Ensure a string can be safely emitted as a Prolog atom."""
    text = str(text).strip()
    # If text is alphanumeric and starts with lowercase, return as is
    if text.isidentifier() and text[0].islower():
        return text
    # Otherwise wrap in single quotes and escape internal quotes
    escaped = text.replace("'", "\\'")
    return f"'{escaped}'"

def format_list(items, is_atom=True) -> str:
    """Format a Python list as a Prolog list string."""
    if not items:
        return "[]"
    if is_atom:
        formatted = [sanitize_atom(x) for x in items]
    else:
        formatted = [repr(x) for x in items]
    return "[" + ", ".join(formatted) + "]"

def load_json_file(path: Path):
    if not path.exists():
        raise FileNotFoundError(f"Required input file missing: {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def main():
    root_dir = Path(__file__).resolve().parent.parent
    data_raw_dir = root_dir / "data" / "raw"
    data_proc_dir = root_dir / "data" / "processed"
    kb_dir = root_dir / "knowledge_base"

    data_proc_dir.mkdir(parents=True, exist_ok=True)
    kb_dir.mkdir(parents=True, exist_ok=True)

    dest_file = data_raw_dir / "european_destinations.json"
    sites_file = data_raw_dir / "unesco_heritage_sites.json"
    transit_file = data_raw_dir / "intercity_transit.json"

    print(f"[*] Loading raw datasets from {data_raw_dir}...")
    destinations = load_json_file(dest_file)
    heritage_sites = load_json_file(sites_file)
    transit_connections = load_json_file(transit_file)

    # Referential validation
    dest_ids = {d["destination_id"] for d in destinations}
    all_topics = set()
    all_eras = set()

    print(f"[*] Validating referential integrity across {len(destinations)} destinations and {len(heritage_sites)} heritage sites...")
    for site in heritage_sites:
        ref_dest = site.get("destination_id")
        if ref_dest not in dest_ids:
            raise ValueError(f"Integrity error: Site '{site['site_id']}' references unknown destination '{ref_dest}'.")
        for topic in site.get("educational_topics", []):
            all_topics.add(topic)
        all_eras.add(site.get("historical_era"))

    # 1. Generate kb_destinations.pl
    kb_dest_path = kb_dir / "kb_destinations.pl"
    print(f"[*] Emitting Prolog facts to {kb_dest_path}...")
    with open(kb_dest_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% European Tour Destinations Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: destination(Id, Name, Country, Region, DailyAccCost, DailyFoodCost, DailyTransportCost, BestSeasons).\n")
        f.write("%         destination_logistics(Id, WalkabilityScore, TransitScore, CulturalVibes).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic destination/8.\n")
        f.write(":- dynamic destination_logistics/4.\n\n")

        for d in destinations:
            d_id = sanitize_atom(d["destination_id"])
            d_name = sanitize_atom(d["name"])
            country = sanitize_atom(d["country"])
            region = sanitize_atom(d["region"])
            acc_cost = float(d["daily_accommodation_cost"])
            food_cost = float(d["daily_food_cost"])
            trans_cost = float(d["daily_transport_cost"])
            seasons = format_list(d["best_seasons"], is_atom=True)

            f.write(f"destination({d_id}, {d_name}, {country}, {region}, {acc_cost:.2f}, {food_cost:.2f}, {trans_cost:.2f}, {seasons}).\n")

        f.write("\n% --- Destination Logistics and Cultural Vibe ---\n")
        for d in destinations:
            d_id = sanitize_atom(d["destination_id"])
            walk = int(d.get("walkability_score", 8))
            transit = int(d.get("transit_score", 8))
            vibes = format_list(d.get("cultural_vibe", []), is_atom=True)
            f.write(f"destination_logistics({d_id}, {walk}, {transit}, {vibes}).\n")

    # 2. Generate kb_heritage.pl
    kb_sites_path = kb_dir / "kb_heritage.pl"
    print(f"[*] Emitting Prolog facts to {kb_sites_path}...")
    with open(kb_sites_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% UNESCO World Heritage Sites Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: heritage_site(SiteId, SiteName, DestinationId, Category, CriteriaList, HistoricalEra,\n")
        f.write("%                       TopicsList, EducationLevel, VisitHours, EntryFee, EduScore).\n")
        f.write("%         heritage_site_logistics(SiteId, WheelchairAccessible, IndoorOutdoor).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic heritage_site/11.\n")
        f.write(":- dynamic heritage_site_logistics/3.\n\n")

        for s in heritage_sites:
            s_id = sanitize_atom(s["site_id"])
            s_name = sanitize_atom(s["name"])
            d_id = sanitize_atom(s["destination_id"])
            cat = sanitize_atom(s["category"])
            criteria = format_list(s.get("unesco_criteria", []), is_atom=True)
            era = sanitize_atom(s.get("historical_era", "unknown"))
            topics = format_list(s.get("educational_topics", []), is_atom=True)
            edu_level = sanitize_atom(s.get("target_education_level", "all"))
            duration = float(s.get("visit_duration_hours", 2.0))
            fee = float(s.get("admission_fee_eur", 0.0))
            edu_score = int(s.get("educational_value_score", 5))

            f.write(f"heritage_site({s_id}, {s_name}, {d_id}, {cat}, {criteria}, {era}, {topics}, {edu_level}, {duration:.1f}, {fee:.2f}, {edu_score}).\n")

        f.write("\n% --- Heritage Site Logistics & Accessibility ---\n")
        for s in heritage_sites:
            s_id = sanitize_atom(s["site_id"])
            wheelchair = "true" if s.get("wheelchair_accessible", True) else "false"
            in_out = sanitize_atom(s.get("indoor_outdoor", "mixed"))
            f.write(f"heritage_site_logistics({s_id}, {wheelchair}, {in_out}).\n")

    # 3. Generate kb_transit.pl
    kb_transit_path = kb_dir / "kb_transit.pl"
    print(f"[*] Emitting Prolog facts to {kb_transit_path}...")
    with open(kb_transit_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Inter-City Transit Connections Knowledge Base\n")
        f.write("% Auto-generated by scripts/build_kb.py\n")
        f.write("% Schema: intercity_transit(OriginDestId, TargetDestId, DurationHours, CostEur, TransitMode).\n")
        f.write("% =========================================================================\n\n")
        f.write(":- dynamic intercity_transit/5.\n\n")

        for t in transit_connections:
            orig = sanitize_atom(t["origin"])
            dest = sanitize_atom(t["destination"])
            dur = float(t["duration_hours"])
            cost = float(t["cost_eur"])
            mode = sanitize_atom(t["mode"])
            f.write(f"intercity_transit({orig}, {dest}, {dur:.1f}, {cost:.2f}, {mode}).\n")

    # 4. Generate load_kb.pl
    kb_loader_path = kb_dir / "load_kb.pl"
    print(f"[*] Creating Knowledge Base loader at {kb_loader_path}...")
    with open(kb_loader_path, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% Knowledge Base Loader Module\n")
        f.write("% Loads all modular knowledge base fact files into the Prolog runtime.\n")
        f.write("% =========================================================================\n\n")
        f.write(":- module(load_kb, [\n")
        f.write("    reload_kb/0,\n")
        f.write("    kb_stats/0,\n")
        f.write("    destination/8,\n")
        f.write("    destination_logistics/4,\n")
        f.write("    heritage_site/11,\n")
        f.write("    heritage_site_logistics/3,\n")
        f.write("    intercity_transit/5\n")
        f.write("]).\n\n")
        f.write(":- dynamic destination/8.\n")
        f.write(":- dynamic destination_logistics/4.\n")
        f.write(":- dynamic heritage_site/11.\n")
        f.write(":- dynamic heritage_site_logistics/3.\n")
        f.write(":- dynamic intercity_transit/5.\n\n")
        f.write(":- consult('kb_destinations.pl').\n")
        f.write(":- consult('kb_heritage.pl').\n")
        f.write(":- consult('kb_transit.pl').\n\n")
        f.write("reload_kb :-\n")
        f.write("    consult('kb_destinations.pl'),\n")
        f.write("    consult('kb_heritage.pl'),\n")
        f.write("    consult('kb_transit.pl'),\n")
        f.write("    writeln('[*] Knowledge base successfully reloaded.').\n\n")
        f.write("kb_stats :-\n")
        f.write("    aggregate_all(count, destination(_,_,_,_,_,_,_,_), DestCount),\n")
        f.write("    aggregate_all(count, heritage_site(_,_,_,_,_,_,_,_,_,_,_), SiteCount),\n")
        f.write("    aggregate_all(count, intercity_transit(_,_,_,_,_), TransitCount),\n")
        f.write("    format('~n=== Knowledge Base Statistics ===~n'),\n")
        f.write("    format('Destinations loaded:       ~w~n', [DestCount]),\n")
        f.write("    format('UNESCO Sites loaded:       ~w~n', [SiteCount]),\n")
        f.write("    format('Transit Corridors loaded:  ~w~n', [TransitCount]),\n")
        f.write("    format('=================================~n~n').\n")

    # 5. Processed summary analytics
    summary = {
        "destinations_count": len(destinations),
        "heritage_sites_count": len(heritage_sites),
        "transit_corridors_count": len(transit_connections),
        "educational_topics": sorted(list(all_topics)),
        "historical_eras": sorted(list(all_eras)),
        "destinations": [d["destination_id"] for d in destinations]
    }
    summary_path = data_proc_dir / "merged_kb_summary.json"
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"[+] Knowledge base ETL complete!")
    print(f"    - {len(destinations)} destinations")
    print(f"    - {len(heritage_sites)} UNESCO heritage sites")
    print(f"    - {len(transit_connections)} transit corridors")
    print(f"    - {len(all_topics)} unique educational disciplines")
    print(f"    - Summary written to {summary_path}")

if __name__ == "__main__":
    main()
