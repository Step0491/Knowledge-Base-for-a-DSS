#!/usr/bin/env python3
"""
generate_kb.py
Utility script to load JSON datasets (Spotify + Smartwatch)
and generate the normalized Prolog facts in 'knowledge_base.pl'.
"""

import json
from pathlib import Path

def sanitize(text: str) -> str:
    """Format a string as a safe Prolog atom."""
    text = str(text).strip().replace("'", "\\'")
    return f"'{text}'"

def format_list(items) -> str:
    """Format a Python list as a Prolog list string."""
    elements = [sanitize(x) for x in items]
    return "[" + ", ".join(elements) + "]"

def main():
    root = Path(__file__).resolve().parent
    tracks_file = root / "data" / "spotify_tracks.json"
    users_file = root / "data" / "smartwatch_biometrics.json"
    kb_file = root / "knowledge_base.pl"

    print("[*] Loading raw JSON datasets...")
    with open(tracks_file, "r", encoding="utf-8") as f:
        tracks = json.load(f)
    with open(users_file, "r", encoding="utf-8") as f:
        users = json.load(f)

    print(f"[*] Emitting Prolog facts to {kb_file.name}...")
    with open(kb_file, "w", encoding="utf-8") as f:
        f.write("% =========================================================================\n")
        f.write("% KNOWLEDGE BASE PROLOG: Decision Support System (DSS)\n")
        f.write("% Automatically generated by generate_kb.py from Spotify & Smartwatch data\n")
        f.write("% =========================================================================\n\n")

        f.write("% --- Facts: track(Id, Title, Artist, Genre, BPM, Valence, Energy, Instrumentalness) ---\n")
        f.write(":- dynamic track/8.\n\n")
        for t in tracks:
            t_id = t["track_id"]
            title = sanitize(t["title"])
            artist = sanitize(t["artist"])
            genre = t["genre"]
            bpm = float(t["bpm"])
            val = float(t["valence"])
            eng = float(t["energy"])
            inst = float(t["instrumentalness"])
            f.write(f"track({t_id}, {title}, {artist}, {genre}, {bpm:.1f}, {val:.2f}, {eng:.2f}, {inst:.2f}).\n")

        f.write("\n% --- Facts: user(Id, Name, Activity, HeartRate, StressLevel, TargetGoal, PreferredGenres) ---\n")
        f.write(":- dynamic user/7.\n\n")
        for u in users:
            u_id = u["user_id"]
            name = sanitize(u["name"])
            act = u["current_activity"]
            hr = float(u["heart_rate_bpm"])
            stress = float(u["stress_level"])
            goal = u["target_health_goal"]
            genres = format_list(u.get("preferred_genres", []))
            f.write(f"user({u_id}, {name}, {act}, {hr:.1f}, {stress:.1f}, {goal}, {genres}).\n")

    print(f"[+] Knowledge base compiled successfully: {len(tracks)} tracks and {len(users)} user profiles written to {kb_file.name}.")

if __name__ == "__main__":
    main()
